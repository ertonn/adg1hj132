// Naive CMYK is too hot for brand colour; these are the Adobe-rendered equivalents.
const BRAND = { navy: "#262261", orange: "#f47b20" };
const H = 992.126;

// Flip PDF's y-up axis into SVG's y-down and drop to one decimal.
const flip = (d) => d.replace(/(-?[\d.]+) (-?[\d.]+)/g, (_, x, y) => `${+(+x).toFixed(1)} ${+(H - y).toFixed(1)}`);

const navy = [...(byFill["#00007d"] ?? []), ...(byFill["#00037e"] ?? [])].map(flip);
const orange = (byFill["#ff580a"] ?? []).map(flip);
// Ordered by the classification above: left stem, lower swoosh, upper swoosh, right tip.
const [stem, lower, upper, tip] = navy;

writeFileSync("assets/js/site/logo-paths.js",
  `// Generated by tools/pdf-logo.mjs from the source logo PDF. Do not hand-edit.\n` +
  `export const MARK = {\n` +
  `  stem: "${stem}",\n  lower: "${lower}",\n  upper: "${upper}",\n  tip: "${tip}",\n` +
  `};\nexport const VIEWBOX = "10 38 1100 840";\nexport const BRAND = ${JSON.stringify(BRAND)};\n`);

writeFileSync("assets/img/logo-full.svg",
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1133.9 992.1" role="img" aria-label="Nevila Samarxhi Akulli — design">` +
  navy.map((d) => `<path fill="${BRAND.navy}" d="${d}"/>`).join("") +
  orange.map((d) => `<path fill="${BRAND.orange}" d="${d}"/>`).join("") +
  `</svg>`);

console.log("wrote assets/js/site/logo-paths.js and assets/img/logo-full.svg");

